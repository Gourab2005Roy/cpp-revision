// Conditional statement.

// The work of conditional statement is to check the condition and accordingly print out..
// If the condition is valid, then it will print the block of 'if', else it will print 'else' block..


// Simple example.
#include<iostream>

int main()
{
    int x = 10;

    if(x == 10)
    {
        std::cout<<"Yes!!";
    }
    else
    {
        std::cerr<<"No!!";
    }

    return 0;
}